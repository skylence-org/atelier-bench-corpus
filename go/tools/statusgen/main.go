// Command statusgen writes the RepairStatus label table.
//
// It is invoked by the //go:generate directive in core/support/status.go and
// its output is committed, so `go generate ./core/support` must reproduce
// core/support/status_labels_gen.go byte for byte.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// labels is the single source of truth for the generated table.
var labels = [][2]string{
	{"StatusReceived", "Received"},
	{"StatusDiagnosing", "Diagnosing"},
	{"StatusAwaitingParts", "Awaiting parts"},
	{"StatusRepairing", "Repairing"},
	{"StatusCompleted", "Completed"},
	{"StatusCollected", "Collected"},
}

func main() {
	out := flag.String("out", "status_labels_gen.go", "file to write")
	flag.Parse()
	formatted, err := format.Source([]byte(render()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "statusgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "statusgen:", err)
		os.Exit(1)
	}
}

// render builds the whole file, gofmt-shaped, with no trailing whitespace.
func render() string {
	var builder strings.Builder
	builder.WriteString("// Code generated by tools/statusgen. DO NOT EDIT.\n\n")
	builder.WriteString("package support\n\n")
	builder.WriteString("// statusLabels is the generated human-facing table.\n")
	builder.WriteString("var statusLabels = map[RepairStatus]string{\n")
	for _, row := range labels {
		builder.WriteString(fmt.Sprintf("\t%s: %q,\n", row[0], row[1]))
	}
	builder.WriteString("}\n\n")
	builder.WriteString("// Label is the generated accessor; String stays hand-written in status.go.\n")
	builder.WriteString("func (s RepairStatus) Label() string {\n")
	builder.WriteString("\treturn statusLabels[s]\n")
	builder.WriteString("}\n")
	return builder.String()
}
